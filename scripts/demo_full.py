"""Q-SHIELD integrated demonstration (Phase 11): one reproducible, end-to-end run on the REAL gateway.

    python scripts/demo_full.py                 # full story, no camera
    python scripts/demo_full.py --webcam        # also run the real webcam + YOLO11n pipeline (ML-KEM session)
    python scripts/demo_full.py --pace 2 --hold # pause 2 s between steps, keep the gateway up for the dashboard

A real FastAPI gateway is started on 127.0.0.1 (uvicorn, in-process thread) against a scratch database and scratch
keys. Every step goes over HTTP through the same code as production: HMAC device auth, ML-DSA-65 signature
verification, trust engine, quarantine enforcement, recovery orchestrator, ML-DSA-signed evidence chain.

Honesty labels printed by the demo:
  SIMULATED  device telemetry comes from the software agent (no ESP32); attacks are generated by attack_simulation/;
             visual violations after the webcam step are synthetic detections signed with the real vision key.
  TIME-LAPSE the trust ramp after remediation needs tens of minutes of clean evidence at the documented parameters;
             the demo advances the gateway clock (and says so) instead of waiting. No parameter is changed for the demo.
"""
